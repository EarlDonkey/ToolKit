"""
Evasion chains: combine multiple bypass techniques into one
assembly, invoked with a single call.

Why chains exist:

  Real EDR monitoring doesn't see events in isolation. It sees them
  in a time sequence. Patching AMSI by itself produces a detectable
  event ("function prologue of amsi.dll!AmsiScanBuffer was
  modified"). Blinding ETW first means the AMSI patch's event never
  gets emitted — the ETW pipeline is dead before the AMSI patch
  happens.

  That's the core insight behind chains: order matters. Get the
  blinding technique in place first, then do the noisy technique.

Presets are curated for two contexts:

  * "modern"  — chains that work against current Defender-enabled
                Windows 11 (October 2026). Only uses techniques
                marked status=works.

  * "legacy"  — chains that reference techniques caught by current
                Defender but useful on older systems or labs with
                Defender disabled.

Chain compilation:

  Techniques are merged into a single assembly with a shared
  namespace and a top-level EvadeChain.Chain.Execute() method that
  invokes each technique in order. See _build_chain_source() for
  the mechanics.
"""

import re
from dataclasses import dataclass

from core.output import info, success, warn, error

from evade import av_bypass


