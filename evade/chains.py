_CHAIN_WRAPPER_HEADER = """\
// Auto-generated evasion chain.
//
// Order matters: techniques are invoked in the sequence they
// were listed. Do not reorder without understanding the
// implications.
//
// Techniques in this chain (in order):
{technique_list}
//
// Generated by: toolkit evade chain
using System;
using System.Reflection;
using System.Runtime.InteropServices;

namespace EvadeChain
{{
{techniques}

    public static class Chain
    {{
        public static void Execute()
        {{
{body}
        }}
    }}
}}
"""


def _sanitize_technique(name: str) -> str:
    """Make a technique name safe for use as a C# identifier."""
    return "".join(c if c.isalnum() or c == "_" else "_"
                   for c in name)


def _extract_class_body(source: str) -> str:
    """Extract a technique's class body from its source.

    The source shape is:
        <using statements>
        namespace <Ns>
        {
            public static class <Class>
            {
                <body>
            }
        }

    We want just the class definition. So we:
      1. Strip using directives
      2. Strip the namespace declaration and its enclosing braces
    """
    # Step 1: remove using directives
    source = re.sub(
        r"^\s*using\s+[^;]+;\s*$",
        "",
        source,
        flags=re.MULTILINE,
    )

    # Step 2: find the namespace block
    m = re.search(r"namespace\s+[A-Za-z0-9_.]+\s*\{", source)
    if m is None:
        return source.strip()

    start = m.end()
    depth = 1
    i = start
    while i < len(source) and depth > 0:
        c = source[i]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
        i += 1

    if depth != 0:
        return source.strip()

    return source[start:i - 1].strip()


def _wrap_technique_class(body: str, technique_name: str,
                           original_class_name: str) -> str:
    """Rename a technique's class to `T_<technique>` and indent."""
    safe = _sanitize_technique(technique_name)

    # Replace "public static class <Original>" with our renamed version
    pattern = re.compile(
        r"\bpublic\s+static\s+class\s+" +
        re.escape(original_class_name) + r"\b",
        re.IGNORECASE,
    )
    renamed = pattern.sub(
        f"public static class T_{safe}",
        body,
        count=1,
    )
    if renamed == body:
        # Fallback for non-public classes
        pattern2 = re.compile(
            r"\bclass\s+" + re.escape(original_class_name) + r"\b")
        renamed = pattern2.sub(
            f"class T_{safe}", body, count=1)

    # Indent for nesting inside namespace braces
    indented = "\n".join(
        ("    " + line) if line.strip() else line
        for line in renamed.splitlines()
    )
    return indented


def _build_chain_source(techniques: list[tuple[str, str]]) -> str:
    """Build the full C# source for a chain."""
    technique_blocks = []
    body_lines = []

    for name, src in techniques:
        spec = av_bypass.TECHNIQUES.get(name, {})
        original_class = spec.get("class", "").split(".")[-1]
        method = spec.get("method", "Patch")

        if not original_class:
            technique_blocks.append(
                f"    // WARNING: could not resolve class for {name}")
            continue

        body = _extract_class_body(src)
        wrapped = _wrap_technique_class(body, name, original_class)
        technique_blocks.append(
            f"    // ----- technique: {name} -----\n{wrapped}")

        safe = _sanitize_technique(name)
        body_lines.append(f"            T_{safe}.{method}();")

    header = _CHAIN_WRAPPER_HEADER.format(
        technique_list="\n".join(
            f"//   {i+1}. {name}"
            for i, (name, _) in enumerate(techniques)),
        techniques="\n\n".join(technique_blocks),
        body="\n".join(body_lines),
    )
    return header


